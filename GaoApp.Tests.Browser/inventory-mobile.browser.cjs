        assert.equal((await noteItem.locator('.timeline-preview-text').innerText()).trim(),'UI12 native phone note');
        await noteItem.locator('button[data-bs-toggle=collapse]').click();
        await noteItem.locator('.collapse.show').waitFor({state:'visible'});
        assert.equal((await noteItem.locator('.timeline-note-full').innerText()).trim(),'UI12 native phone note');
