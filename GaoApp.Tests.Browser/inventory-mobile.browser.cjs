        assert.equal(await valuationQuantity.first().isVisible(),false);
        await page.setViewportSize({width:768,height:1000});await mobile.settle(page);
        assert.equal(await page.locator('.adj-phone-revaluation-note,[data-adjustment-phone-revaluation]').count(),0);
        assert.deepEqual(await valuationQuantity.allTextContents(),originalValuationText);
        assert.equal(await valuationQuantity.first().isVisible(),true);
        await page.setViewportSize({width:390,height:844});await mobile.settle(page);
        assert.equal(await page.locator('.adj-phone-revaluation-note').isVisible(),true);
