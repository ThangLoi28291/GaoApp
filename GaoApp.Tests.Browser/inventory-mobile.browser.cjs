        await page.locator('#adjOpenMobileFilters').click();
        await mobile.dialog(page,'#inventoryAdjustmentMobileFilterSheet','adjustment-filters',info.output);
        await page.locator('#inventoryAdjustmentMobileFilterSheet [data-bs-dismiss=offcanvas]').click();
        await page.locator('#inventoryAdjustmentMobileFilterSheet').waitFor({state:'hidden'});
        await page.locator(`#adjMobileList [data-document-id="${info.revaluationId}"] .adj-index-quick-button`).click();
        await page.waitForFunction(()=>document.getElementById('inventoryAdjustmentQuickViewBody')?.textContent.includes('Lốc 4'));
        await mobile.dialog(page,'#inventoryAdjustmentQuickViewModal','adjustment-quick-view',info.output);
