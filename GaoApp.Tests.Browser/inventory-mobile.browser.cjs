        await page.locator('#Note').fill('UI12 native phone increase, edited through original view');
        await mobile.review(page,'adjustment-edit',info.output,{root:'.adj-page'});
        await Promise.all([page.waitForURL(url=>url.pathname===`/admin/inventory-adjustment-documents/${adjustmentId}`),page.locator('#btnSaveDocument').click()]);await adjustmentReady();
