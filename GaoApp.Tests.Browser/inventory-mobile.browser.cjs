        await createdPage;
        const adjustmentId=Number(new URL(page.url()).pathname.split('/').pop());
        assert.ok(Number.isSafeInteger(adjustmentId)&&adjustmentId>0);
        await adjustmentReady();
        await mobile.review(page,'adjustment-draft',info.output,{root:'.adj-page'});
        await page.locator(`#actionBox a[href$="/${adjustmentId}/edit"]`).click();
        await page.waitForFunction(()=>document.querySelector('#AdjustmentLineTableBody .js-line-note')&&document.getElementById('Note')?.value==='UI12 native phone increase');
