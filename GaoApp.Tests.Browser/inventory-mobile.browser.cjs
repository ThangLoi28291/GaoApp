        await mobile.dialog(page,'.swal2-popup','adjustment-native-quantity',info.output);
        await page.locator('#popupQty').fill('1.5');
        await page.locator('#popupInputCost').fill('40');
        assert.equal((await page.locator('#popupBaseQty').innerText()).trim(),'6');
        await page.locator('.swal2-confirm').click();
        await page.waitForFunction(()=>document.querySelector('#AdjustmentLineTableBody .js-line-note'));
        await page.keyboard.press('Escape');
        await mobile.review(page,'adjustment-create-factor4',info.output,{root:'.adj-page'});
