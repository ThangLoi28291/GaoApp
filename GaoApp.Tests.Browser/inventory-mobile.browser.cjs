        await Promise.all([page.waitForNavigation({waitUntil:'domcontentloaded'}),noteForm.locator('[type=submit]').click()]);
        assert.equal((await notePosted).status(),302);
        assert.equal(new URL(page.url()).pathname,`/admin/inventory-issues/${info.issueId}`);
        assert.match(await page.locator('.inventory-issue-detail-page .alert-success').innerText(),/Đã thêm ghi chú/);
        assert.equal(await noteForm.locator('[name=Note]').inputValue(),'');
