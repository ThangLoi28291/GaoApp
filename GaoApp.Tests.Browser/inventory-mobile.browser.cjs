        await page.locator('#WarehouseId').selectOption(String(info.warehouseId));
        await page.locator('#AdjustmentType').selectOption('30');
        await page.locator('#ReasonType').selectOption('5');
        await page.locator('#Note').fill('UI12 native phone increase');
        await page.locator('#ProductQuickSearch + .select2 .select2-selection').click();
        const search=page.locator('.select2-container--open .select2-search__field');
        await search.fill('');
        const lookup=page.waitForResponse(response=>{
            const url=new URL(response.url());return response.request().method()==='GET'&&url.pathname==='/admin/api/inventory-adjustments/product-lookup-select2'&&url.searchParams.get('term')===info.barcode;
        });
        await search.pressSequentially(info.barcode);
        const lookupResponse=await lookup;assert.equal(lookupResponse.status(),200);
        const matched=(await lookupResponse.json()).results.find(item=>item.productUnitConversionId===info.conversionId);
        assert.ok(matched,'Original numeric barcode lookup returns the seeded conversion');
        assert.equal(matched.unitId,info.unitId);assert.equal(matched.factor,4);assert.equal(matched.barcode,info.barcode);
        await page.locator('.select2-results__option[aria-selected],.select2-results__option--selectable').filter({hasText:info.barcode}).first().click();
