        await page.locator('.inventory-issue-detail-page').waitFor({state:'visible'});
        await mobile.review(page,'issue-case-source',info.output,{root:'.inventory-issue-detail-page'});
        const noteForm=page.locator('form[action$="/add-note"]');
        await noteForm.locator('[name=Note]').fill('UI12 native phone note');
